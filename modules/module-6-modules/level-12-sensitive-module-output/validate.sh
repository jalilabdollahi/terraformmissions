#!/usr/bin/env bash
source "$TM_LIB"

tm_assert_config_lacks 'nonsensitive[[:space:]]*\(' "nonsensitive() would leak the code — keep it a secret"
tm_assert_config_has 'random_password' "the code has to keep being generated by random_password"

tm_init
TM_MSG="terraform apply failed — read which output Terraform says refers to sensitive values" tm_apply

tm_assert_in_state module.room.random_password.door

CODE=$(tm_output_raw door_code) || tm_fail "output door_code does not exist"
[[ "$CODE" =~ ^[0-9]{6}$ ]] || tm_fail "door_code is '$CODE', expected exactly six digits"
tm_assert_file_equals keys/booking.txt "DOOR ${CODE}"$'\n'

LISTING=$(terraform output -no-color 2>/dev/null)
grep -q "door_code *= *<sensitive>" <<<"$LISTING" || tm_fail "terraform output must show door_code as <sensitive>"
grep -qF "$CODE" <<<"$LISTING" && tm_fail "the code leaks in the plain 'terraform output' listing"

# Stable across runs, and the length input still reaches the generator
tm_assert_no_changes
tm_apply -var code_length=9
CODE9=$(tm_output_raw door_code)
[[ "$CODE9" =~ ^[0-9]{9}$ ]] || tm_fail "with code_length=9 the code is '$CODE9' — expected nine digits"
tm_assert_file_equals keys/booking.txt "DOOR ${CODE9}"$'\n'

tm_apply
tm_assert_no_changes
if ! grep -qE 'sensitive[[:space:]]*=[[:space:]]*true' modules/room/main.tf 2>/dev/null; then
  tm_fail "the module's own output has to be marked sensitive"
fi
tm_pass "the door code stays sensitive from the module to the root output"
