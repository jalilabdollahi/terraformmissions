#!/usr/bin/env bash
source "$TM_LIB"

T=tests/booth.tftest.hcl
tm_assert_file "$T" "tests/booth.tftest.hcl is missing"
[[ -f tests/setup/main.tf ]] || tm_fail "the helper module tests/setup is gone"

python3 - "$T" <<'PY'
import re, sys
text = open(sys.argv[1]).read()
parts = re.split(r'^run\s+"', text, flags=re.M)[1:]
runs = {p.split('"', 1)[0]: p for p in parts}
order = [p.split('"', 1)[0] for p in parts]
if order != ["setup", "short_programme", "setup_long", "double_bill"]:
    print("runs must be setup, short_programme, setup_long, double_bill; found %s" % order); sys.exit(2)
for h in ("setup", "setup_long"):
    b = runs[h]
    if not re.search(r'module\s*\{\s*source\s*=\s*"\./tests/setup"', b):
        print("%s must target ./tests/setup" % h); sys.exit(3)
    m = re.search(r'command\s*=\s*(\w+)', b)
    if m and m.group(1) != "apply":
        print("%s must apply: a plan creates no manifest" % h); sys.exit(4)
for consumer, helper in (("short_programme", "setup"), ("double_bill", "setup_long")):
    b = runs[consumer]
    if "run.%s.manifest_path" % helper not in b:
        print("%s must read run.%s.manifest_path" % (consumer, helper)); sys.exit(5)
    if re.search(r'module\s*\{', b):
        print("%s must test the root module, not a helper" % consumer); sys.exit(6)
PY
rc=$?
[[ $rc -eq 0 ]] || tm_fail "the helper-run pattern is not right yet (check $rc): helpers target tests/setup, apply, and feed the runs that follow"

tm_init
tm_tf test -verbose
if [[ $? -ne 0 ]]; then
  tm_show_last
  tm_fail "terraform test is failing"
fi
grep -q '^Success! 4 passed, 0 failed' "$TM_LAST_OUT" || tm_fail "four runs must pass"
[[ ! -e tests/setup/manifest.json ]] || tm_fail "a manifest was left behind in tests/setup - fixtures must be created and destroyed by the helper run"

dent() {
  local why="$1" old="$2" new="$3" d="$TM_TMP/dent-$1"
  rm -rf "$d"; mkdir -p "$d"; cp -R ./. "$d"/
  python3 - "$d/booth.tf" "$old" "$new" <<'PY'
import sys
p, a, b = sys.argv[1:4]
s = open(p).read()
t = s.replace(a, b)
open(p, "w").write(t)
sys.exit(0 if s != t else 3)
PY
  [[ $? -eq 0 ]] || return 0
  (cd "$d" && terraform test -no-color) >"$TM_TMP/dent.out" 2>&1 && tm_fail "the suite passes although $why"
}
dent "the intermission limit is far too high" 'minutes]) > 120' 'minutes]) > 400'
dent "minutes are counted as reels" 'value = sum([for r in local.reels : r.minutes])' 'value = length(local.reels)'
tm_pass "fixtures are generated by applied helper runs, consumed by chaining, and cleaned up"
